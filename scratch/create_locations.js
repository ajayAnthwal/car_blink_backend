/**
 * Sorted list of all 36 Indian States and Union Territories.
 */
export const INDIAN_STATES: string[] = Object.keys(INDIAN_CITIES_BY_STATE).sort();

/**
 * Get cities for a given state name (case-insensitive fallback).
 */
export function getCitiesForState(stateName?: string): string[] {
  if (!stateName || !stateName.trim()) {
    return [];
  }
  const cleanState = stateName.trim();
  if (INDIAN_CITIES_BY_STATE[cleanState]) {
    return INDIAN_CITIES_BY_STATE[cleanState];
  }
  // Case-insensitive fallback
  const foundKey = Object.keys(INDIAN_CITIES_BY_STATE).find(
    (k) => k.toLowerCase() === cleanState.toLowerCase()
  );
  return foundKey ? INDIAN_CITIES_BY_STATE[foundKey] : [];
}

/**
 * Flattens all unique cities across India.
 */
export function getAllCities(): string[] {
  const citySet = new Set<string>();
  Object.values(INDIAN_CITIES_BY_STATE).forEach((cities) => {
    cities.forEach((c) => citySet.add(c));
  });
  return Array.from(citySet).sort();
}
